#!/usr/bin/env python3
"""Build ../timeline.ts for "Calonnya Cicilan" from lines.json (cue segments + speaker), lips.json (narrator loudness) and the SHOTS table below.
No Whisper needed: the words of every cue are spread over the cue using the narrator's loudness envelope (so words land on the sound, pauses stay pauses).
usage: python3 tools/build_timeline.py          (run from src/videos/02_rania_cicilan)"""
import json, re, os
HERE = os.path.dirname(os.path.abspath(__file__)); OUT = os.path.join(HERE, '..', 'timeline.ts')
DUR = 104.52; VOICE_END = 104.9
# name, start (s).  Insert shots (thr, cup, tally, sign, nota, cal, bub) are tiny sets away from the party (see set.tsx)
SHOTS = [('open1', 0), ('open2', 1.5), ('open3', 2.5), ('thr', 3.5), ('door', 6.2), ('wide1', 9.0), ('nenek1', 10.5), ('rania1', 12.3), ('two1', 14.9),
 ('rina1', 17.7), ('rania2', 20.9), ('dewi1', 24.2), ('dewi2', 26.1), ('rania3', 28.5), ('budi1', 32.2), ('budi2', 35.5), ('rina2', 37.2), ('rina3', 41.9),
 ('tea1', 44.4), ('rania4', 46.6), ('tally', 48.0), ('rania5', 50.9), ('rina4', 52.4), ('rina5', 55.0), ('wide2', 58.94), ('tea2', 60.5), ('rania6', 62.8),
 ('rina6', 66.0), ('rania7', 69.0), ('sign1', 72.7), ('sign2', 73.55), ('sign3', 74.35), ('rania8', 75.2), ('wide3', 76.9), ('nota', 80.4), ('rania9', 83.0),
 ('rania10', 86.2), ('cal', 87.2), ('dewi3', 88.9), ('budi3', 91.4), ('two2', 93.8), ('wide4', 97.1), ('bub', 99.7), ('two3', 101.6)]
L = json.load(open(os.path.join(HERE, 'lines.json'))); P = json.load(open(os.path.join(HERE, 'lips.json'))); o = P['o']
words = []
for seg in L:
    ws = seg['text'].replace('"', '').replace('\u201c', '').replace('\u201d', '').split()
    if not ws: continue
    k0, k1 = int(seg['t0'] * 24), max(int(seg['t0'] * 24) + 1, int(seg['t1'] * 24))
    e = [(o[k] if k < len(o) else 0) + 0.12 for k in range(k0, k1)]; cum = [0.0]
    for v in e: cum.append(cum[-1] + v)
    wt = [len(re.sub(r'\W', '', w)) + 1.5 + (1.5 if re.search(r'[,.?!;:]$', w) else 0) for w in ws]; tot = sum(wt); acc = 0.0
    def at(frac):  # fraction of the cue's energy -> seconds
        target = frac * cum[-1]
        for i in range(1, len(cum)):
            if cum[i] >= target:
                a, b = cum[i - 1], cum[i]; return (k0 + (i - 1) + (target - a) / max(1e-9, b - a)) / 24
        return seg['t1']
    for w, x in zip(ws, wt):
        s = at(acc / tot); acc += x; en = min(at(acc / tot), seg['t1'])
        if words and s < words[-1][1] + 0.02: s = words[-1][1] + 0.02
        words.append([w, round(s, 3), round(max(s + 0.08, en - 0.02), 3)])
caps, i = [], 0
while i < len(words):
    j = i
    while j + 1 < len(words) and j - i < 2 and not re.search(r'[,.?!;:]$', words[j][0]) and words[j + 1][1] - words[j][2] <= 0.25: j += 1
    caps.append([i, j]); i = j + 1
speech = [[s['who'], s['t0'], s['t1']] for s in L]
J = lambda x: json.dumps(x, ensure_ascii=False)
shot_real = {n: t for n, t in SHOTS}
src = f'''// GENERATED by tools/build_timeline.py (identity timeline: staging clock = voice clock). Do not edit by hand.
export const FPS = 30;
export const OLD_TOTAL = {round(VOICE_END * 30)};
export const WORDS: [string, number, number][] = {J(words)};
export const CAPS: [number, number][] = {J(caps)};
export const SHOT_START: Record<string, number> = {J({n: round(t * 30) for n, t in SHOTS})};
export const SHOT_REAL: Record<string, number> = {J(shot_real)};
export const WORDS_REAL: [string, number, number][] = WORDS;
export const END_REAL = {VOICE_END};
export const VOICE_END = {VOICE_END};
export const WARP: [number, number][] = [[0, 0], [{VOICE_END}, {VOICE_END}]];
export const warp = (t: number) => t;
/** who speaks when (N = narrator): drives the mouths */
export const SPEECH: [string, number, number][] = {J(speech)};
'''
open(OUT, 'w').write(src); print('shots', len(SHOTS), 'words', len(words), 'caps', len(caps))
